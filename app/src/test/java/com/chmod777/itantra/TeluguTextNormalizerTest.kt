    @Test
    fun cardinalsMatchIndicNumToWords() {
        for ((n, words) in reference) {
            assertEquals("n=$n", words, TeluguTextNormalizer.verbalize(n.toString()))
        }
    }

    @Test
    fun teluguAndAsciiDigitsBothBecomeWords() {
        assertEquals("మందుల కోసం పన్నెండు పెట్టెలు తీసుకురండి",
            TeluguTextNormalizer.normalize("మందుల కోసం ౧౨ పెట్టెలు తీసుకురండి"))
        assertEquals("మందుల కోసం పన్నెండు పెట్టెలు తీసుకురండి",
            TeluguTextNormalizer.normalize("మందుల కోసం 12 పెట్టెలు తీసుకురండి"))
    }

    @Test
    fun leadingZeroAndLongRunsAreReadDigitByDigit() {
        assertEquals("సున్నా ఒకటి ఏడు", TeluguTextNormalizer.normalize("౦౧౭"))
        assertEquals(
            "ఒకటి రెండు మూడు నాలుగు ఐదు ఆరు ఏడు ఎనిమిది తొమ్మిది సున్నా",
            TeluguTextNormalizer.verbalize("1234567890")
        )
        assertEquals("సున్నా", TeluguTextNormalizer.normalize("౦"))
    }

    @Test
    fun textWithoutDigitsIsUnchangedApartFromNfc() {
        val s = "నది నీరు వేగంగా పెరుగుతోంది. సురక్షిత ప్రదేశానికి వెళ్లండి."
        assertEquals(java.text.Normalizer.normalize(s, java.text.Normalizer.Form.NFC), TeluguTextNormalizer.normalize(s))
    }
