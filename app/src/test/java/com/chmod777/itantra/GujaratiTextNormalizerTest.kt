    @Test
    fun cardinalsMatchIndicNumToWords() {
        for ((n, words) in reference) {
            assertEquals("n=$n", words, GujaratiTextNormalizer.verbalize(n.toString()))
        }
    }

    @Test
    fun gujaratiAndAsciiDigitsBothBecomeWordsAttachedToClassifier() {
        assertEquals("દવા માટે બાર બોક્સ લઈ આવો", GujaratiTextNormalizer.normalize("દવા માટે ૧૨ બોક્સ લઈ આવો"))
        assertEquals("દવા માટે બાર બોક્સ લઈ આવો", GujaratiTextNormalizer.normalize("દવા માટે 12 બોક્સ લઈ આવો"))
        assertEquals("બસો પચાસ જણ", GujaratiTextNormalizer.normalize("૨૫૦ જણ"))
    }

    @Test
    fun leadingZeroAndLongRunsAreReadDigitByDigit() {
        assertEquals("શૂન્ય એક સાત", GujaratiTextNormalizer.normalize("૦૧૭"))
        assertEquals("એક બે ત્રણ ચાર પાંચ છ સાત આઠ નવ શૂન્ય", GujaratiTextNormalizer.verbalize("1234567890"))
        assertEquals("શૂન્ય", GujaratiTextNormalizer.normalize("૦"))
    }

    @Test
    fun textWithoutDigitsIsUnchangedApartFromNfc() {
        val s = "નદીનું પાણી ઝડપથી વધી રહ્યું છે"
        assertEquals(java.text.Normalizer.normalize(s, java.text.Normalizer.Form.NFC), GujaratiTextNormalizer.normalize(s))
    }
