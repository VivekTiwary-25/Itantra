            "ஒன்று இரண்டு மூன்று நான்கு ஐந்து ஆறு ஏழு எட்டு ஒன்பது பூஜ்ஜியம்",
            TamilTextNormalizer.verbalize("1234567890")
        )
        assertEquals("பூஜ்ஜியம்", TamilTextNormalizer.normalize("0"))
    }

    @Test
    fun decomposedVowelSignsAreComposedToMatchVocabulary() {
        // ொ/ோ/ௌ (U+0BCA/0BCB/0BCC) each canonically decompose to two codepoints that are both
        // individually present in the vocabulary; NFC must fold them back to the single token
        // tokens.txt actually defines.
        val decomposed = "கொ" // க + ெ + ா  ->  கொ
        assertEquals("கொ", TamilTextNormalizer.normalize(decomposed))
    }

    @Test
    fun textWithoutDigitsIsUnchangedApartFromNfc() {
        val s = "ஆற்று நீர் வேகமாக உயர்கிறது. பாதுகாப்பான இடத்திற்கு செல்லுங்கள்."
        assertEquals(
            java.text.Normalizer.normalize(s, java.text.Normalizer.Form.NFC),
            TamilTextNormalizer.normalize(s)
        )
    }
