    @Test
    fun tamilAndAsciiDigitsBothBecomeWordsAttachedToClassifier() {
        // "8" is confirmed absent from the MMS Tamil vocabulary even as an ASCII character
        // (tools/mms_desktop_probe.py against tokens.txt reported U+0038 as OOV).
        assertEquals(
            "மருந்துக்காக பன்னிரண்டு பெட்டிகள் கொண்டு வாருங்கள்.",
            TamilTextNormalizer.normalize("மருந்துக்காக 12 பெட்டிகள் கொண்டு வாருங்கள்.")
        )
        assertEquals(
            "மருந்துக்காக பன்னிரண்டு பெட்டிகள் கொண்டு வாருங்கள்.",
            TamilTextNormalizer.normalize("மருந்துக்காக ௧௨ பெட்டிகள் கொண்டு வாருங்கள்.")
        )
        assertEquals("எட்டு பேர்", TamilTextNormalizer.normalize("8 பேர்"))
    }

