    @Test
    fun cardinalsMatchIndicNumToWords() {
        for ((n, words) in reference) {
            assertEquals("n=$n", words, BengaliTextNormalizer.verbalize(n.toString()))
        }
    }

    @Test
    fun bengaliAndAsciiDigitsBothBecomeWordsAttachedToClassifier() {
        assertEquals("ওষুধের জন্য বারোটি বাক্স", BengaliTextNormalizer.normalize("ওষুধের জন্য ১২টি বাক্স"))
        assertEquals("ওষুধের জন্য বারোটি বাক্স", BengaliTextNormalizer.normalize("ওষুধের জন্য 12টি বাক্স"))
        assertEquals("দুশো পঞ্চাশ জন", BengaliTextNormalizer.normalize("২৫০ জন"))
    }

    @Test
    fun leadingZeroAndLongRunsAreReadDigitByDigit() {
        assertEquals("শূন্য এক সাত", BengaliTextNormalizer.normalize("০১৭"))
        assertEquals("এক দুই তিন চার পাঁচ ছয় সাত আট নয় শূন্য", BengaliTextNormalizer.verbalize("1234567890"))
        assertEquals("শূন্য", BengaliTextNormalizer.normalize("০"))
    }

    @Test
    fun precomposedNuktaLettersAreDecomposed() {
        // U+09DC/U+09DD/U+09DF are not in the MMS vocabulary; base letter + U+09BC are.
        assertEquals("ড়ঢ়য়", BengaliTextNormalizer.normalize("ড়ঢ়য়"))
    }

    @Test
    fun textWithoutDigitsIsUnchangedApartFromNfc() {
        val s = "নদীর পানি দ্রুত বাড়ছে। নিরাপদ জায়গায় যান।"
        assertEquals(java.text.Normalizer.normalize(s, java.text.Normalizer.Form.NFC), BengaliTextNormalizer.normalize(s))
    }
